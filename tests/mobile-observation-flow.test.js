import assert from 'node:assert/strict';
import { effectScope, ref } from 'vue';
import { emptyCheckin, generateMobileReport, usableDeviceSample, storeSessionReport, loadSessionReport } from '../src/services/mobile-diagnosis.service.js';
import { useCheckinDraft, readDraft, draftStorageKey } from '../src/composables/useCheckinDraft.js';

const storage = new Map();
globalThis.localStorage = { getItem: (key) => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
const account = ref('account-a');
const scope = effectScope();
let state;
scope.run(() => { state = useCheckinDraft(account); });
state.draft.value.tempC = 24.3;
state.draft.value.elapsedHours = 4;
state.draft.value.ph = 3.9;
state.draft.value.sources.tempC = '设备读取';
account.value = 'account-b';
assert.equal(state.draft.value.tempC, '');
state.draft.value.tempC = 30;
account.value = 'account-a';
assert.equal(state.draft.value.tempC, 24.3);
assert.equal(state.draft.value.elapsedHours, 4);
assert.equal(state.draft.value.ph, 3.9);
assert.equal(state.draft.value.sources.tempC, '设备读取');
scope.stop();
storage.set(draftStorageKey('disk-account'), JSON.stringify({ tempC: 25.5, elapsedHours: 0, ph: 4.1 }));
assert.equal(readDraft('disk-account', 'checkin', emptyCheckin()).tempC, 25.5);
const base = { ...emptyCheckin(), color: 'normal', smell: 'normal', height: 'slight', stage: 'mature', ratio: '1:2:2', elapsedHours: 4 };
const risk = generateMobileReport({ ...emptyCheckin(), color: 'suspicious' }, 'account-a').report;
assert.equal(risk.result.status, 'discard');
assert.equal(risk.result.timing, undefined);
assert.equal(generateMobileReport({ ...emptyCheckin(), color: 'unknown', smell: 'normal' }, 'account-a').report.result.status, 'needs-check');
// Use an actual supported height without depending on presentation labels.
const { mobileOptions } = await import('../src/services/mobile-diagnosis.service.js');
base.height = mobileOptions.height[0].value;
const report = generateMobileReport(base, 'account-a').report;
assert.ok(report);
assert.equal(report.result.timing, undefined);
storeSessionReport('account-a', report);
report.input.tempC = 99;
assert.equal(loadSessionReport('account-a').input.tempC, '');
assert.equal(loadSessionReport('account-b'), null);
const now = Date.now();
const sample = { recorded_at: new Date(now - 60000).toISOString(), mode: 'fer', sensor_error: false };
const link = { active_from: new Date(now - 120000).toISOString(), active_to: null };
assert.equal(usableDeviceSample(sample, link, now), true);
assert.equal(usableDeviceSample({ ...sample, sensor_error: true }, link, now), false);
assert.equal(usableDeviceSample({ ...sample, mode: 'sleep' }, link, now), false);
assert.equal(usableDeviceSample(sample, { ...link, active_from: new Date(now).toISOString() }, now), false);
assert.equal(usableDeviceSample(sample, link, now + 41 * 60000), false);
console.log('mobile observation flow: OK');
