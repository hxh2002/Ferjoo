begin;

create schema if not exists private;
revoke all on schema private from public;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'user_role' and typnamespace = 'public'::regnamespace) then
    create type public.user_role as enum ('U', 'A');
  end if;
end
$$;

create table if not exists private.user_id_counters (
  role public.user_role not null,
  period char(4) not null,
  last_value integer not null check (last_value between 1 and 9999),
  primary key (role, period)
);

create or replace function private.allocate_system_user_id(p_role public.user_role)
returns varchar
language plpgsql
security definer
set search_path = private, public, pg_temp
as $$
declare
  v_period char(4) := to_char(timezone('UTC', now()), 'YYMM');
  v_sequence integer;
begin
  insert into private.user_id_counters(role, period, last_value)
  values (p_role, v_period, 1)
  on conflict (role, period)
  do update set last_value = private.user_id_counters.last_value + 1
  returning last_value into v_sequence;

  if v_sequence > 9999 then
    raise exception 'User ID sequence exhausted for role % period %', p_role, v_period;
  end if;

  return (p_role::text || v_period || lpad(v_sequence::text, 4, '0'))::varchar;
end;
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  system_user_id varchar(9) not null unique,
  role public.user_role not null default 'U',
  email text not null,
  display_name varchar(80),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_system_user_id_format
    check (system_user_id ~ '^[UA][0-9]{8}$')
);

create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_role public.user_role := 'U';
begin
  insert into public.profiles(id, system_user_id, role, email, display_name)
  values (
    new.id,
    private.allocate_system_user_id(v_role),
    v_role,
    coalesce(new.email, ''),
    nullif(new.raw_user_meta_data ->> 'display_name', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_auth_user();

create or replace function private.sync_auth_email()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.email is distinct from old.email then
    update public.profiles
    set email = coalesce(new.email, ''), updated_at = now()
    where id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
after update of email on auth.users
for each row execute function private.sync_auth_email();

create or replace function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
before update on public.profiles
for each row execute function private.touch_updated_at();

create table if not exists public.devices (
  device_id varchar(80) primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  name varchar(80),
  model varchar(80),
  firmware_version varchar(40),
  last_seen_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint devices_device_id_not_blank check (length(trim(device_id)) > 0),
  constraint devices_device_owner_unique unique (device_id, user_id)
);

drop trigger if exists devices_touch_updated_at on public.devices;
create trigger devices_touch_updated_at
before update on public.devices
for each row execute function private.touch_updated_at();

create table if not exists public.device_measurements (
  id bigint generated by default as identity primary key,
  device_id varchar(80) not null,
  user_id uuid not null default auth.uid(),
  recorded_at timestamptz not null default now(),
  bucket_start timestamptz not null default now(),
  temperature_c numeric(5,2),
  height_mm numeric(10,3),
  height_delta_mm numeric(10,3),
  humidity_percent numeric(5,2),
  battery_percent numeric(5,2),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint device_measurements_device_owner_fk
    foreign key (device_id, user_id)
    references public.devices(device_id, user_id)
    on delete cascade,
  constraint device_measurements_humidity_range
    check (humidity_percent is null or humidity_percent between 0 and 100),
  constraint device_measurements_battery_range
    check (battery_percent is null or battery_percent between 0 and 100),
  constraint device_measurements_one_point_per_bucket
    unique (device_id, bucket_start)
);

create or replace function private.set_measurement_bucket()
returns trigger
language plpgsql
set search_path = pg_temp
as $$
begin
  new.bucket_start := date_bin(
    interval '10 minutes',
    new.recorded_at,
    timestamptz '2000-01-01 00:00:00+00'
  );
  return new;
end;
$$;

drop trigger if exists device_measurements_bucket on public.device_measurements;
create trigger device_measurements_bucket
before insert or update of recorded_at on public.device_measurements
for each row execute function private.set_measurement_bucket();

create or replace function private.touch_device_last_seen()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.devices
  set last_seen_at = greatest(coalesce(last_seen_at, new.recorded_at), new.recorded_at)
  where device_id = new.device_id and user_id = new.user_id;
  return new;
end;
$$;

drop trigger if exists device_measurements_touch_device on public.device_measurements;
create trigger device_measurements_touch_device
after insert on public.device_measurements
for each row execute function private.touch_device_last_seen();

create index if not exists devices_user_id_idx
  on public.devices(user_id, created_at desc);

create index if not exists device_measurements_user_time_idx
  on public.device_measurements(user_id, bucket_start desc);

create index if not exists device_measurements_device_time_idx
  on public.device_measurements(device_id, bucket_start desc);

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid() and role = 'A'
  );
$$;

-- Role changes are deliberately server-side only.
-- Because public/system IDs encode role, changing U <-> A allocates a new display ID.
-- Internal UUID foreign keys remain stable, so device/history relationships are unaffected.
create or replace function private.set_user_role(p_user_id uuid, p_role public.user_role)
returns varchar
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_system_user_id varchar;
begin
  v_system_user_id := private.allocate_system_user_id(p_role);

  update public.profiles
  set role = p_role,
      system_user_id = v_system_user_id,
      updated_at = now()
  where id = p_user_id;

  if not found then
    raise exception 'Unknown user %', p_user_id;
  end if;

  return v_system_user_id;
end;
$$;

alter table public.profiles enable row level security;
alter table public.devices enable row level security;
alter table public.device_measurements enable row level security;

revoke all on table public.profiles from anon, authenticated;
revoke all on table public.devices from anon, authenticated;
revoke all on table public.device_measurements from anon, authenticated;

grant usage on type public.user_role to authenticated;
grant usage on schema private to authenticated;
grant execute on function private.is_admin() to authenticated;

grant select on table public.profiles to authenticated;
grant update (display_name) on table public.profiles to authenticated;

grant select, insert, update, delete on table public.devices to authenticated;
grant select, insert on table public.device_measurements to authenticated;
grant usage, select on sequence public.device_measurements_id_seq to authenticated;

drop policy if exists profiles_select_own_or_admin on public.profiles;
create policy profiles_select_own_or_admin
on public.profiles for select
to authenticated
using ((select auth.uid()) = id or private.is_admin());

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own
on public.profiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

drop policy if exists devices_select_own_or_admin on public.devices;
create policy devices_select_own_or_admin
on public.devices for select
to authenticated
using ((select auth.uid()) = user_id or private.is_admin());

drop policy if exists devices_insert_own_or_admin on public.devices;
create policy devices_insert_own_or_admin
on public.devices for insert
to authenticated
with check ((select auth.uid()) = user_id or private.is_admin());

drop policy if exists devices_update_own_or_admin on public.devices;
create policy devices_update_own_or_admin
on public.devices for update
to authenticated
using ((select auth.uid()) = user_id or private.is_admin())
with check ((select auth.uid()) = user_id or private.is_admin());

drop policy if exists devices_delete_own_or_admin on public.devices;
create policy devices_delete_own_or_admin
on public.devices for delete
to authenticated
using ((select auth.uid()) = user_id or private.is_admin());

drop policy if exists measurements_select_own_or_admin on public.device_measurements;
create policy measurements_select_own_or_admin
on public.device_measurements for select
to authenticated
using ((select auth.uid()) = user_id or private.is_admin());

drop policy if exists measurements_insert_own_or_admin on public.device_measurements;
create policy measurements_insert_own_or_admin
on public.device_measurements for insert
to authenticated
with check ((select auth.uid()) = user_id or private.is_admin());

create or replace view public.device_latest_measurements
with (security_invoker = true)
as
select distinct on (device_id)
  device_id,
  user_id,
  bucket_start,
  recorded_at,
  temperature_c,
  height_mm,
  height_delta_mm,
  humidity_percent,
  battery_percent
from public.device_measurements
order by device_id, bucket_start desc;

revoke all on table public.device_latest_measurements from anon, authenticated;
grant select on table public.device_latest_measurements to authenticated;

revoke all on function private.allocate_system_user_id(public.user_role) from public, anon, authenticated;
revoke all on function private.set_user_role(uuid, public.user_role) from public, anon, authenticated;
revoke all on function private.handle_new_auth_user() from public, anon, authenticated;
revoke all on function private.sync_auth_email() from public, anon, authenticated;
revoke all on function private.touch_device_last_seen() from public, anon, authenticated;

commit;
